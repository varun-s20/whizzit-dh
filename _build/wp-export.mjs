// Exports the site for WordPress: the shared chrome into the child theme, every
// page's content into the plugin's data file, and the design assets into the
// theme. Usage: node _build/wp-export.mjs
//
// Pages are matched to WordPress by URL path, so the same data works on the dev,
// staging and live installs whatever their post IDs are.
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { readdirSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

process.env.WHIZZIT_EXPORT = "wp";
const { wpRecords } = await import("./lib.mjs");

const pagesDir = join(import.meta.dirname, "pages");
for (const file of readdirSync(pagesDir).filter((f) => f.endsWith(".mjs")).sort()) {
  await import(pathToFileURL(join(pagesDir, file)).href);
}

const root = join(import.meta.dirname, "..");
const theme = join(root, "wordpress", "whizzit-child");
const plugin = join(root, "wordpress", "whizzit-core");

// Chrome: generated, never edited by hand.
mkdirSync(join(theme, "parts"), { recursive: true });
const banner = "<!-- Generated by _build/wp-export.mjs. Edit _build/lib.mjs, not this file. -->\n";
for (const [name, html] of Object.entries(wpRecords.chrome)) {
  const file = name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
  writeFileSync(join(theme, "parts", `${file}.html`), banner + html.trim() + "\n");
}

// Assets: the design's own CSS, JS and images. Stock originals (the .jpg sources
// behind the resized photos) stay out.
const assets = join(theme, "assets");
rmSync(assets, { recursive: true, force: true });
cpSync(join(root, "assets", "css"), join(assets, "css"), { recursive: true });
cpSync(join(root, "assets", "js"), join(assets, "js"), { recursive: true });
cpSync(join(root, "assets", "images"), join(assets, "images"), {
  recursive: true,
  filter: (src) => !/[\\/]stock([\\/]|$)/.test(src) && !/README\.txt$/.test(src),
});

// Page content: one record per URL path, as a list of Elementor widgets.
mkdirSync(join(plugin, "data"), { recursive: true });
const { splitTop, slotify } = await import("./wp-sections.mjs");
const templates = new Map();
// Posts are exported separately below (posts.json); pages.json holds pages only.
const pages = wpRecords.pages
  .filter((p) => !(p.path.startsWith("/blog/") && p.path !== "/blog/"))
  .sort((a, b) => a.path.localeCompare(b.path))
  .map(({ main, ...page }) => {
    const widgets = splitTop(main).map((chunk) => {
      if (chunk.kind === "struct") return { widget: chunk.type, settings: chunk.settings };
      const sec = slotify(chunk.html);
      if (!templates.has(sec.id)) {
        templates.set(sec.id, { id: sec.id, title: sec.title, template: sec.template, uses: 0, slots: sec.slots.map(({ k, type, label, value }) => ({ k, type, label, default: value })) });
      }
      templates.get(sec.id).uses += 1;
      // Text and links are this page's own words; images keep their markup.
      const values = Object.fromEntries(sec.slots.map((s) => (s.type === "i" ? [`${s.k}_html`, s.value.html] : [s.k, s.value])));
      return { widget: "section", tpl: sec.id, settings: values };
    });
    return { ...page, widgets };
  });
writeFileSync(join(plugin, "data", "pages.json"), JSON.stringify({ generated: new Date().toISOString(), pages }));

// Section templates: one file each (loaded only when that widget renders), an
// index for registration, and a named PHP class per template, since Elementor
// needs one class per widget type.
const secDir = join(plugin, "data", "sections");
rmSync(secDir, { recursive: true, force: true });
mkdirSync(secDir, { recursive: true });
for (const t of templates.values()) writeFileSync(join(secDir, `${t.id}.json`), JSON.stringify(t));
const index = [...templates.values()].map(({ id, title, uses }) => ({ id, title, uses }));
writeFileSync(join(secDir, "index.json"), JSON.stringify(index));
const php = [
  "<?php",
  "// Generated by _build/wp-export.mjs: one Elementor widget class per section template.",
  "// Loaded inside elementor/widgets/register, after Elementor's classes exist.",
  "defined( 'ABSPATH' ) || exit;",
  ...index.map((t) => `final class WhizzIT_Section_${t.id} extends \\WhizzIT\\Widgets\\Section { const TPL = '${t.id}'; }`),
  "return [ " + index.map((t) => `'WhizzIT_Section_${t.id}'`).join(", ") + " ];",
  "",
].join("\n");
writeFileSync(join(plugin, "inc", "generated-sections.php"), php);
const fields = [...templates.values()].reduce((n, t) => n + t.slots.length, 0);
const structured = pages.reduce((n, p) => n + p.widgets.filter((w) => w.widget !== "section").length, 0);
console.log(`Sections: ${templates.size} templates (${fields} fields), ${structured} structured blocks, ${pages.reduce((n, p) => n + p.widgets.length, 0)} widgets across ${pages.length} pages.`);

// Blog posts: the clean article body (hero, forms and layout come from the
// theme's single.php), flattened onto one line so WordPress's wpautop cannot
// scatter <br> tags through it.
const { BLOG, SERVICES, STOCK, CATEGORY_PHOTO, wpUrls } = await import("./lib.mjs");
const { BLOG_CATEGORIES } = await import("./site.mjs");
const { icon, iconNames } = await import("./icons.mjs");
const flat = (html) => html.replace(/\s*\n\s*/g, " ").trim();
const posts = BLOG.map((p) => ({
  slug: p.slug, title: p.title, excerpt: p.excerpt, author: p.author, date: p.date, read: p.read,
  category: p.category, body: flat(wpUrls(p.body)),
}));
writeFileSync(join(plugin, "data", "posts.json"), JSON.stringify({ posts }, null, 1));

// Blog categories: label, tone and icon (from the posts that use them) and the
// stock photo that stands in for a missing featured image.
const look = Object.fromEntries(BLOG.map((p) => [p.category, { tone: p.tone, icon: p.icon }]));
const categories = BLOG_CATEGORIES.filter((c) => c.key !== "all").map((c) => {
  const stock = STOCK[CATEGORY_PHOTO[c.key]] || STOCK.team;
  return { slug: c.key, label: c.label, used: c.key in look, ...(look[c.key] || { tone: "support", icon: "book" }), photo: stock.slug };
});
writeFileSync(join(plugin, "data", "categories.json"), JSON.stringify({ categories }, null, 1));

// Services, for the "Related service" card on each post.
const services = SERVICES.map((s) => ({ key: s.key, title: s.title, url: wpUrls(`@/${s.href}`), short: s.short, icon: s.icon, tone: s.tone }));
writeFileSync(join(plugin, "data", "services.json"), JSON.stringify({ services }, null, 1));

// Sectors: become the "sector" post type on import. The stock photo stands in
// until a sector has a featured image of its own.
const { INDUSTRIES, SECTOR_PHOTO } = await import("./lib.mjs");
const { SECTOR_NOTE } = await import("./pages/industries.mjs");
const sectors = INDUSTRIES.map((s) => ({
  key: s.key, path: wpUrls(`@/${s.href}`), label: s.title, icon: s.icon, desc: s.desc, note: SECTOR_NOTE[s.key] || "",
  photo: (STOCK[SECTOR_PHOTO[s.key]] || STOCK.meeting).slug,
}));
writeFileSync(join(plugin, "data", "sectors.json"), JSON.stringify({ sectors }, null, 1));

// The icon set, so PHP prints exactly the same SVGs.
writeFileSync(join(plugin, "data", "icons.json"), JSON.stringify(Object.fromEntries(iconNames().map((n) => [n, icon(n)]))));

console.log(`Posts: ${posts.length}, categories: ${categories.filter((c) => c.used).length} used of ${categories.length}, services: ${services.length}, icons: ${iconNames().length}.`);

const kinds = pages.reduce((n, p) => ((n[p.path.startsWith("/blog/") && p.path !== "/blog/" ? "posts" : "pages"] += 1), n), { pages: 0, posts: 0 });
console.log(`Exported ${pages.length} records (${kinds.pages} pages, ${kinds.posts} posts), chrome, and assets.`);
